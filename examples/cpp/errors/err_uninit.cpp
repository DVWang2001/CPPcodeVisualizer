// 錯誤教案 #4：未初始化的變數
// BUG：sum 沒有初始化，它的初值是記憶體裡的隨機殘留值，不是 0。
// 學生常見想法：「區域變數預設是 0」（C++ 內建型別的區域變數不會自動清零）。
// 修正：int sum = 0;
// 註：本來的值是棧上殘留的垃圾。在某些環境（例如 Linux 把棧頁清零）它剛好是 0，
//     結果看起來「正確」，這正是此錯誤最危險的地方；換環境或換編譯器就會錯。
#include <iostream>

int main() {
    int sum;                        // BUG：忘了 = 0
    std::cout << "一開始 sum = " << sum << "（應該是 0）" << std::endl;
    for (int i = 1; i <= 5; i++) {
        sum += i;                   // 每次都是加在不確定的初值上
    }
    std::cout << "1+2+3+4+5 = " << sum << "（應為 15）" << std::endl;
    return 0;
}
